const mongoose = require('mongoose');
// const bcrypt = require('bcrypt');
const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const User = require('../models/User');
require('dotenv').config();

/**
 * Scanner Service Account Creator
 * 
 * Creates a dedicated user account for the scanner service.
 * This user can then be used to generate a long-lived JWT token.
 * 
 * Usage: node create-scanner-user.js
 */

const createScannerAccount = async () => {
  try {
    // Connect to MongoDB
    const mongoUri = process.env.MONGODB_URI;
    await mongoose.connect(mongoUri);
    console.log('✓ Connected to MongoDB\n');

    const JWT_SECRET = process.env.JWT_SECRET;
    if (!JWT_SECRET) {
      console.error('ERROR: JWT_SECRET not found in .env');
      process.exit(1);
    }

    // Check if scanner account already exists
    let scannerUser = await User.findOne({ email: 'scanner@dms.local' });

    if (scannerUser) {
      console.log('Scanner account already exists:');
      console.log(`  User ID: ${scannerUser._id}`);
      console.log(`  Name:    ${scannerUser.name}`);
      console.log(`  Email:   ${scannerUser.email}`);
      console.log(`  Role:    ${scannerUser.role}`);
      console.log(`  Status:  ${scannerUser.status}`);
      console.log('\nTo generate a new token for this user, run:');
      console.log(`  SCANNER_USER_ID=${scannerUser._id} node generate-scanner-token.js`);
    } else {
      // Create scanner service account
      console.log('Creating scanner service account...');

      const hashedPassword = await bcrypt.hash('ScannerService2024!', 12);

      scannerUser = await User.create({
        name: 'Scanner Service',
        email: 'scanner@dms.local',
        password: hashedPassword,
        role: 'admin',  // Adjust if you want more restrictive permissions
        department: 'scanner',
        status: 'active',
        confidentialityLevels: ['public', 'internal', 'confidential', 'highly_confidential']
      });

      console.log('✓ Scanner account created!');
      console.log(`  User ID: ${scannerUser._id}`);
      console.log(`  Email:   ${scannerUser.email}`);
      console.log(`  Role:    ${scannerUser.role}`);
    }

    // Generate token
    const token = jwt.sign(
      {
        id: scannerUser._id,
        email: scannerUser.email,
        name: scannerUser.name,
        role: scannerUser.role,
        department: scannerUser.department,
        scanner: true
      },
      JWT_SECRET,
      { expiresIn: '365d' }
    );

    console.log('\n=== Scanner Token ===');
    console.log(token);
    console.log('=====================\n');

    // Save token and user ID to watcher/.env
    const fs = require('fs');
    const path = require('path');
    const watcherEnvPath = path.resolve(__dirname, '../../watcher/.env');

    console.log(`\nWriting to watcher .env at: ${watcherEnvPath}`);

    let envContent = `# Scanner Watcher Configuration\n`;
    envContent += `# Auto-generated by create-scanner-user.js\n`;
    envContent += `# Generated: ${new Date().toISOString()}\n\n`;
    envContent += `SCAN_DIR=C:/Users/user/Documents/Scan\n`;
    envContent += `SCANNER_API_URL=https://rhv-dms-backend.vercel.app/api/v1/scanner/upload\n`;
    envContent += `SCANNER_USER_ID=${scannerUser._id}\n`;
    envContent += `SCANNER_TOKEN=${token}\n`;
    envContent += `DELETE_AFTER_UPLOAD=true\n`;
    envContent += `UPLOAD_DELAY_MIN=1000\n`;
    envContent += `UPLOAD_DELAY_MAX=2000\n`;

    try {
      fs.writeFileSync(watcherEnvPath, envContent);
      console.log(`✓ Written to: ${watcherEnvPath}\n`);
    } catch (writeErr) {
      console.error(`⚠ Could not write to ${watcherEnvPath}: ${writeErr.message}`);
      console.error('Please manually copy the token below to watcher/.env:\n');
    }

    await mongoose.disconnect();
    console.log('Disconnected from MongoDB\n');

    console.log('Setup complete!');
    console.log('\nNext steps:');
    console.log('1. Verify SCANNER_TOKEN is set in watcher/.env');
    console.log('2. Start the watcher: cd watcher && npm start');
    console.log('3. Place scanned files in your scan folder\n');

    process.exit(0);
  } catch (error) {
  console.error('Error:', error.message);
  if (error.name === 'MongoServerSelectionError') {
    console.error('\nMake sure MongoDB is running on localhost:27017');
  }
  process.exit(1);
}
};

createScannerAccount();
